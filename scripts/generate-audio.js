#!/usr/bin/env node
/**
 * Generate pre-recorded audio for every phrase using macOS `say`, so the
 * Speak button does NOT depend on the browser's speechSynthesis (which is
 * unreliable/broken on iOS Safari). The app plays these files through a plain
 * <audio> element — the same mechanism as the "Hear what you said" replay,
 * which is known to work on iPhone.
 *
 * Outputs:
 *   - assets/audio/<sha1>.m4a      one AAC (.m4a) file per phrase
 *   - assets/js/audio-map.js       zh -> file path lookup used by the app
 *   - assets/audio/manifest.json   file list used by the service worker
 *
 * Requires macOS with a Chinese voice installed (Sandy / Tingting / …).
 * Re-run this script after adding or changing any phrase.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const DATA_JS = path.join(ROOT, 'assets', 'js', 'data.js');
const AUDIO_DIR = path.join(ROOT, 'assets', 'audio');
const VOICE = process.env.MTP_VOICE || 'Sandy (Chinese (China mainland))';
// Speaking rate in words per minute. The macOS default (~175) is too fast for
// language learners, so we record slower (~135) — slower cadence with natural
// pitch (unlike an <audio> playbackRate slowdown, which drops the pitch).
const RATE = process.env.MTP_RATE || '135';
const FORCE = process.argv.includes('--force') || process.env.MTP_FORCE === '1';

function loadPhrasebook() {
  const code = fs.readFileSync(DATA_JS, 'utf8');
  const window = {};
  // data.js attaches to `window.Phrasebook` (it checks `typeof window !== 'undefined'`).
  // eslint-disable-next-line no-new-func
  new Function('window', code + '\n;return window.Phrasebook;')(window);
  return window.Phrasebook;
}

// Strip ellipsis placeholders ("我叫…", "我要去…") so TTS doesn't read them.
function ttsText(zh) {
  return zh.replace(/…|\.\.\./g, '').trim();
}

function fileFor(categoryId, zh) {
  const h = crypto.createHash('sha1').update(categoryId + '|' + zh).digest('hex').slice(0, 12);
  return h + '.m4a';
}

function main() {
  const pb = loadPhrasebook();
  fs.mkdirSync(AUDIO_DIR, { recursive: true });

  const map = {};   // zh -> relative path
  const files = []; // relative paths

  const tmp = path.join(AUDIO_DIR, '.tmp.aiff');

  const entries = [];
  for (const cat of pb.CATEGORIES) {
    for (const phrase of pb.PHRASES[cat.id] || []) {
      entries.push({ cat: cat.id, zh: phrase.zh });
    }
  }

  let i = 0;
  for (const e of entries) {
    i += 1;
    const clean = ttsText(e.zh);
    const fname = fileFor(e.cat, e.zh);
    const rel = 'assets/audio/' + fname;
    const abs = path.join(AUDIO_DIR, fname);

    if (FORCE || !fs.existsSync(abs)) {
      execFileSync('say', ['-v', VOICE, '-r', RATE, '-o', tmp, clean], { stdio: 'ignore' });
      execFileSync('afconvert', ['-f', 'm4af', '-d', 'aac', tmp, abs], { stdio: 'ignore' });
    }

    map[e.zh] = rel;
    files.push(rel);
    if (i % 20 === 0 || i === entries.length) {
      process.stdout.write('\r  ' + i + '/' + entries.length + ' generated');
    }
  }

  try { fs.unlinkSync(tmp); } catch (err) { /* ignore */ }

  const mapJs = '/* AUTO-GENERATED by scripts/generate-audio.js — do not edit. */\n' +
    '(function (global) {\n' +
    "  'use strict';\n" +
    '  global.Phrasebook = global.Phrasebook || {};\n' +
    '  global.Phrasebook.AUDIO = ' + JSON.stringify(map, null, 2) + ';\n' +
    "})(typeof window !== 'undefined' ? window : this);\n";
  fs.writeFileSync(path.join(ROOT, 'assets', 'js', 'audio-map.js'), mapJs);

  fs.writeFileSync(path.join(AUDIO_DIR, 'manifest.json'), JSON.stringify(files, null, 2));

  console.log('\nDone: ' + files.length + ' audio files -> ' + AUDIO_DIR);
  console.log('Wrote assets/js/audio-map.js and assets/audio/manifest.json');
}

main();
