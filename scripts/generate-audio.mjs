#!/usr/bin/env node
/**
 * Generate high-quality phrase audio from the macOS voices and store them for
 * the Next.js server: public/audio/<voice>/<speed>/<hash>.m4a
 *
 * Two speeds are recorded so the app can offer a "Normal / Slow" toggle that
 * keeps natural pitch in both modes (a plain <audio> playbackRate slowdown
 * would drop the pitch and sound robotic).
 *
 * Produces:
 *   - public/audio/<voice>/<speed>/<sha1>.m4a   one AAC file per phrase/voice/speed
 *   - lib/audio-map.js                          exports VOICES + SPEED_MODES + AUDIO
 *
 * Usage:
 *   node scripts/generate-audio.mjs            # skip already-generated files
 *   node scripts/generate-audio.mjs --force    # regenerate everything
 *
 * Requires macOS with the listed Chinese voices installed.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { CATEGORIES, PHRASES } from '../lib/data.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const AUDIO_DIR = path.join(ROOT, 'public', 'audio');
const MAP_FILE = path.join(ROOT, 'lib', 'audio-map.js');
const FORCE = process.argv.includes('--force') || process.env.MTP_FORCE === '1';

// Words per minute for each speed mode (macOS default is ~175).
const RATES = {
  normal: process.env.MTP_RATE_NORMAL || '135',
  slow: process.env.MTP_RATE_SLOW || '100'
};

// Available Chinese (China mainland) voices on this Mac. More than one so the
// user can pick the one they like best. Add/remove entries freely, then rerun.
const VOICES = [
  { id: 'sandy',   say: 'Sandy (Chinese (China mainland))',   label: 'Sandy',    gender: 'female', description: 'Neural female' },
  { id: 'shelley', say: 'Shelley (Chinese (China mainland))', label: 'Shelley',  gender: 'female', description: 'Neural female' },
  { id: 'tingting', say: 'Tingting',                          label: 'Ting-Ting', gender: 'female', description: 'Classic female', default: true },
  { id: 'eddy',    say: 'Eddy (Chinese (China mainland))',    label: 'Eddy',     gender: 'male',   description: 'Neural male' }
];

const ttsText = (zh) => zh.replace(/…|\.\.\./g, '').trim();
const fileFor = (categoryId, zh) =>
  crypto.createHash('sha1').update(categoryId + '|' + zh).digest('hex').slice(0, 12) + '.m4a';

function entries() {
  const out = [];
  for (const cat of CATEGORIES) {
    for (const phrase of PHRASES[cat.id] || []) out.push({ cat: cat.id, zh: phrase.zh });
  }
  return out;
}

function main() {
  const list = entries();
  const AUDIO = {}; // zh -> filename (speed/voice-independent)
  for (const e of list) AUDIO[e.zh] = fileFor(e.cat, e.zh);

  const modes = Object.keys(RATES);
  const total = list.length * VOICES.length * modes.length;
  let done = 0;

  for (const voice of VOICES) {
    for (const mode of modes) {
      const dir = path.join(AUDIO_DIR, voice.id, mode);
      fs.mkdirSync(dir, { recursive: true });
      const tmp = path.join(dir, '.tmp.aiff');

      for (const e of list) {
        const abs = path.join(dir, AUDIO[e.zh]);
        if (FORCE || !fs.existsSync(abs)) {
          execFileSync('say', ['-v', voice.say, '-r', RATES[mode], '-o', tmp, ttsText(e.zh)], { stdio: 'ignore' });
          execFileSync('afconvert', ['-f', 'm4af', '-d', 'aac', tmp, abs], { stdio: 'ignore' });
        }
        done += 1;
        if (done % 40 === 0 || done === total) {
          process.stdout.write('\r  ' + done + '/' + total + ' generated');
        }
      }
      try { fs.unlinkSync(tmp); } catch (err) { /* ignore */ }
    }
  }

  const SPEED_MODES = [
    { id: 'normal', label: '🐇 Normal' },
    { id: 'slow', label: '🐢 Slow' }
  ];

  const mapSrc =
    '// AUTO-GENERATED by scripts/generate-audio.mjs — do not edit.\n' +
    'export const VOICES = ' + JSON.stringify(VOICES.map(({ say, ...v }) => v), null, 2) + ';\n\n' +
    'export const SPEED_MODES = ' + JSON.stringify(SPEED_MODES, null, 2) + ';\n\n' +
    '// zh -> audio filename (relative to /audio/<voice>/<speed>/).\n' +
    'export const AUDIO = ' + JSON.stringify(AUDIO, null, 2) + ';\n';
  fs.writeFileSync(MAP_FILE, mapSrc);

  console.log('\nDone: ' + total + ' files -> ' + AUDIO_DIR);
  console.log('Wrote ' + MAP_FILE);
}

main();
